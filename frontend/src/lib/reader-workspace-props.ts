import type { ReaderWorkspaceProps } from '../components/reader-workspace'
import type { SourceContextMenuController } from '../hooks/use-source-context-menu'
import type { ReaderSidebarState } from '../hooks/use-reader-sidebar-state'
import type { useReaderFeatureSection } from '../hooks/use-reader-feature-section'
import {
  buildCompactTitleParts,
  formatReplyCount,
  formatTimeAgo,
  formatTimeAgoCompact,
  normalizeImageURL,
  plainText,
  truncate,
} from './app-utils'
import { summaryTaskStatusLabel } from './summary-task-utils'
import { threadPreviewCommentLimit, sidebarTagCollapseCount } from './app-domain'

type ReaderWorkspaceInput = {
  sidebarState: ReaderSidebarState
  readerSection: ReturnType<typeof useReaderFeatureSection>
  availableTags: string[]
  onOpenSourceContextMenu: SourceContextMenuController['openSourceContextMenu']
  onOpenSourceContextMenuAt: SourceContextMenuController['openSourceContextMenuAt']
  returnToAILibrary?: () => void
  returnToAILibraryLabel?: string
}

export function buildReaderWorkspaceProps({
  sidebarState,
  readerSection,
  availableTags,
  onOpenSourceContextMenu,
  onOpenSourceContextMenuAt,
  returnToAILibrary,
  returnToAILibraryLabel,
}: ReaderWorkspaceInput): ReaderWorkspaceProps {
  const toggleSidebar = () => sidebarState.setShowSubscriptionSidebar((open) => !open)

  return {
    showSubscriptionSidebar: sidebarState.showSubscriptionSidebar,
    onToggleSubscriptionSidebar: toggleSidebar,
    onCloseSubscriptionSidebar: () => sidebarState.setShowSubscriptionSidebar(false),
    showFloatingReader: readerSection.showFloatingReader,
    readerView: readerSection.readerView,
    sidebarProps: {
      showSubscriptionSidebar: sidebarState.showSubscriptionSidebar,
      sourceFilter: readerSection.sourceFilter,
      readerSources: sidebarState.readerSources,
      sourceGroups: sidebarState.sourceGroups,
      sidebarTagFilterMode: sidebarState.sidebarTagFilterMode,
      sidebarTagFilters: sidebarState.sidebarTagFilters,
      sidebarTagFilterSet: sidebarState.sidebarTagFilterSet,
      showAllSidebarTags: sidebarState.showAllSidebarTags,
      sidebarTagCollapseCount,
      sidebarVisibleFeedSources: sidebarState.sidebarVisibleFeedSources,
      sourceGroupFilterKey: sidebarState.sourceGroupFilter?.key ?? '',
      isSourceGroupFilterActive: Boolean(sidebarState.sourceGroupFilter),
      readerTrackedSources: sidebarState.readerTrackedSources,
      showTrackedSidebar: sidebarState.showTrackedSidebar,
      visibleTrackedSidebarSources: sidebarState.visibleTrackedSidebarSources,
      hasMoreTrackedSidebarSources: sidebarState.hasMoreTrackedSidebarSources,
      showAllTrackedSidebar: sidebarState.showAllTrackedSidebar,
      onToggleSubscriptionSidebar: toggleSidebar,
      onApplySourceFilterFromSidebar: readerSection.applySourceFilterFromSidebar,
      onApplySourceGroupFilterFromSidebar: readerSection.applySourceGroupFilterFromSidebar,
      onSwitchSidebarTagFilterMode: readerSection.switchSidebarTagFilterMode,
      onApplySidebarTagFilters: readerSection.applySidebarTagFilters,
      onToggleShowAllSidebarTags: () => sidebarState.setShowAllSidebarTags((value) => !value),
      onToggleSidebarTagFilter: readerSection.toggleSidebarTagFilter,
      onRegisterSidebarSourceItemRef: readerSection.registerSidebarSourceItemRef,
      onOpenSourceContextMenu,
      onOpenSourceContextMenuAt,
      onToggleShowTrackedSidebar: () => sidebarState.setShowTrackedSidebar((value) => !value),
      onToggleShowAllTrackedSidebar: () => sidebarState.setShowAllTrackedSidebar((value) => !value),
    },
    feedProps: {
      feedMode: readerSection.feedMode,
      onChangeFeedMode: readerSection.onChangeFeedMode,
      showFloatingReader: readerSection.showFloatingReader,
      readerView: readerSection.readerView,
      feedTitleOnlyMode: readerSection.feedTitleOnlyMode,
      showFeedImages: readerSection.showFeedImages,
      showFeedSearch: readerSection.showFeedSearch,
      showAdvancedFilters: readerSection.showAdvancedFilters,
      showFeedAIMoreMenu: readerSection.showFeedAIMoreMenu,
      loadingFeedBriefing: readerSection.loadingFeedBriefing,
      unreadVisibleCount: readerSection.unreadVisibleCount,
      favoriteVisibleCount: readerSection.favoriteVisibleCount,
      unreadOnly: readerSection.unreadOnly,
      favoriteOnly: readerSection.favoriteOnly,
      hasActiveFilters: Boolean(readerSection.hasActiveFilters),
      keyword: readerSection.keyword,
      tagFilter: readerSection.tagFilter,
      sourceFilter: readerSection.sourceFilter,
      mutedSiteKeys: readerSection.mutedSiteKeys,
      availableTags,
      readerSources: sidebarState.readerSources,
      sourceFilterSelectValue: readerSection.sourceFilterSelectValue,
      sourceFilterChipLabel: readerSection.sourceFilterChipLabel,
      loadingFeed: readerSection.loadingFeed,
      feedError: readerSection.feedError,
      feed: readerSection.feed,
      visibleFeed: readerSection.visibleFeed,
      hasFeedBriefingEntry: readerSection.hasFeedBriefingEntry,
      feedBriefingInsertIndex: readerSection.feedBriefingInsertIndex,
      selectedArticleID: readerSection.selectedArticleID,
      selectedFeedBriefing: readerSection.selectedFeedBriefing,
      readArticleIDSet: readerSection.readArticleIDSet,
      favoriteArticleIDSet: readerSection.favoriteArticleIDSet,
      feedAIMoreRef: readerSection.feedAIMoreRef,
      feedAutoLoadRef: readerSection.feedAutoLoadRef,
      hasMoreFeed: readerSection.hasMoreFeed,
      feedBriefingPreviewText: readerSection.feedBriefingPreviewText,
      feedBriefingScopeLabel: readerSection.feedBriefingScopeLabel,
      feedBriefingFreshnessLabel: readerSection.feedBriefingFreshnessLabel,
      feedBriefingNewArticleCount: readerSection.feedBriefingNewArticleCount,
      feedBriefingArticleCount: readerSection.feedBriefingArticleCount,
      feedBriefingItems: readerSection.feedBriefingItems,
      catchUpCheckpoint: readerSection.catchUpCheckpoint,
      catchUpCount: readerSection.catchUpCount,
      catchUpLoading: readerSection.catchUpLoading,
      catchUpError: readerSection.catchUpError,
      onGenerateFeedBriefing: readerSection.onGenerateFeedBriefing,
      onRefreshCatchUp: readerSection.refreshCatchUp,
      onGenerateCatchUpBriefing: readerSection.generateCatchUpBriefing,
      onMarkCaughtUp: readerSection.markCaughtUp,
      onCloseFeedAIMoreMenu: () => readerSection.setShowFeedAIMoreMenu(false),
      onToggleFeedAIMoreMenu: () => readerSection.setShowFeedAIMoreMenu((value) => !value),
      onSetUnreadOnly: readerSection.setUnreadOnly,
      onSetFavoriteOnly: readerSection.setFavoriteOnly,
      onToggleFeedTitleOnlyMode: () => readerSection.setFeedTitleOnlyMode((value) => !value),
      onToggleFeedImages: () => readerSection.setShowFeedImages((value) => !value),
      onToggleFeedSearch: () => {
        readerSection.setShowFeedSearch((value) => {
          const next = !value
          if (!next) {
            readerSection.setShowAdvancedFilters(false)
          }
          return next
        })
      },
      onApplyFilters: readerSection.applyFilters,
      onToggleAdvancedFilters: () => readerSection.setShowAdvancedFilters((value) => !value),
      onChangeKeyword: readerSection.setKeyword,
      onChangeTagFilter: readerSection.setTagFilter,
      onChangeSourceFilter: (value) => {
        readerSection.setSourceGroupFilter(null)
        readerSection.setSidebarTagFilters([])
        readerSection.setSourceFilter(value)
      },
      onClearFilters: readerSection.clearFilters,
      onRemoveFilter: readerSection.removeFilter,
      onRetryLoadFeed: readerSection.retryFeed,
      onOpenArticle: readerSection.openArticle,
      onToggleFavoriteArticle: readerSection.onToggleFavoriteArticle,
      onOpenFeedBriefing: readerSection.openFeedBriefing,
      onLoadMore: readerSection.loadMore,
      normalizeImageURL,
      formatTimeAgo,
      formatTimeAgoCompact,
      formatReplyCount,
      buildCompactTitleParts,
      plainText,
      truncate,
      getSummaryTaskStatus: readerSection.getSummaryTaskStatus,
      summaryTaskStatusLabel,
    },
    detailProps: {
      floatingDetailRef: readerSection.floatingDetailRef,
      showFloatingReader: readerSection.showFloatingReader,
      readerView: readerSection.readerView,
      selectedArticle: readerSection.selectedArticle,
      selectedFeedBriefing: readerSection.selectedFeedBriefing,
      loadingArticle: readerSection.loadingArticle,
      articleError: readerSection.articleError,
      selectedArticleID: readerSection.selectedArticleID,
      openArticle: readerSection.openArticle,
      feedBriefingScopeLabel: readerSection.feedBriefingScopeLabel,
      feedBriefingFreshnessLabel: readerSection.feedBriefingFreshnessLabel,
      returnToReaderStream: readerSection.returnToReaderStream,
      returnToAILibrary,
      returnToAILibraryLabel,
      closeFloatingReader: readerSection.closeFloatingReader,
      openImmersiveReader: readerSection.openImmersiveReader,
      aiModel: readerSection.aiModel,
      onGenerateFeedBriefing: readerSection.onGenerateFeedBriefing,
      loadingFeedBriefing: readerSection.loadingFeedBriefing,
      feedBriefingMeta: readerSection.feedBriefingMeta,
      feedBriefingNewArticleCount: readerSection.feedBriefingNewArticleCount,
      feedBriefingError: readerSection.feedBriefingError,
      feedBriefing: readerSection.feedBriefing,
      feedBriefingItems: readerSection.feedBriefingItems,
      feedBriefingArticleCount: readerSection.feedBriefingArticleCount,
      formatTimeAgo,
      selectedArticleReplyCountLabel: readerSection.selectedArticleReplyCountLabel,
      selectedArticleImageURL: readerSection.selectedArticleImageURL,
      closeDetailMoreMenu: readerSection.closeDetailMoreMenu,
      isFavoriteArticle: readerSection.isFavoriteArticle,
      onToggleFavoriteArticle: readerSection.onToggleFavoriteArticle,
      onSummarizeArticle: readerSection.onSummarizeArticle,
      loadingArticleSummary: readerSection.loadingArticleSummary,
      hasDetailMoreActions: readerSection.hasDetailMoreActions,
      detailMoreMenuRef: readerSection.detailMoreMenuRef,
      showDetailMoreMenu: readerSection.showDetailMoreMenu,
      toggleDetailMoreMenu: readerSection.toggleDetailMoreMenu,
      canTrackThread: readerSection.canTrackThread,
      onTrackThread: readerSection.onTrackThread,
      canForceRecalcSummary: readerSection.canForceRecalcSummary,
      articleSummaryError: readerSection.articleSummaryError,
      articleSummary: readerSection.articleSummary,
      articleSummaryMeta: readerSection.articleSummaryMeta,
      selectedSummaryTask: readerSection.selectedSummaryTask,
      isThreadArticle: readerSection.isThreadArticle,
      threadPrimaryBody: readerSection.threadPrimaryBody,
      visibleThreadComments: readerSection.visibleThreadComments,
      threadComments: readerSection.threadComments,
      threadCommentsNewestFirst: readerSection.threadCommentsNewestFirst,
      onToggleThreadCommentsNewestFirst: () => readerSection.setThreadCommentsNewestFirst((value) => !value),
      threadPreviewCommentLimit,
      expandedThreadComments: readerSection.expandedThreadComments,
      onToggleExpandedThreadComments: () => readerSection.setExpandedThreadComments((value) => !value),
      hasHiddenThreadComments: readerSection.hasHiddenThreadComments,
    },
  }
}
